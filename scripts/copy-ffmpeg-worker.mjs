#!/usr/bin/env node
/**
 * Stage @ffmpeg's runtime files under public/ffmpeg/ so the browser fetches
 * them locally instead of hitting unpkg on every first-load.
 *
 *  - worker.js (inlined) — concatenated worker.js + const.js + errors.js from
 *    @ffmpeg/ffmpeg with imports stripped. Single-file module worker avoids
 *    any MIME / sub-module load failure that would silently hang the worker.
 *    Also bypasses Turbopack's "expression too dynamic" failure on the
 *    worker's runtime `await import(coreURL)`.
 *  - ffmpeg-core.js + ffmpeg-core.wasm (from @ffmpeg/core) — the 31MB wasm.
 *    Self-hosting makes "Loading encoder" near-instant.
 */
import { mkdirSync, copyFileSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const dest = join(root, "public/ffmpeg");
const ffmpegSrc = join(root, "node_modules/@ffmpeg/ffmpeg/dist/esm");
const coreSrc = join(root, "node_modules/@ffmpeg/core/dist/esm");

mkdirSync(dest, { recursive: true });

if (existsSync(ffmpegSrc)) {
  // Inline const.js + errors.js into worker.js so the module worker is one
  // self-contained file. The originals use ESM imports across files; we strip
  // those and concatenate the source-of-truth contents in dependency order.
  const stripImports = (s) =>
    s.replace(/^\s*import\s+[^;]+;?\s*$/gm, "");
  const stripExports = (s) =>
    s.replace(/^\s*export\s+/gm, "");

  const constJs = stripImports(stripExports(readFileSync(join(ffmpegSrc, "const.js"), "utf8")));
  const errorsJs = stripImports(stripExports(readFileSync(join(ffmpegSrc, "errors.js"), "utf8")));
  const workerJs = stripImports(readFileSync(join(ffmpegSrc, "worker.js"), "utf8"));
  const bundled = [
    "// AUTO-GENERATED by scripts/copy-ffmpeg-worker.mjs — do not edit.",
    constJs,
    errorsJs,
    workerJs,
  ].join("\n");
  writeFileSync(join(dest, "worker.js"), bundled);
} else {
  console.warn("[copy-ffmpeg-worker] @ffmpeg/ffmpeg not installed, skipping worker");
}

if (existsSync(coreSrc)) {
  for (const file of ["ffmpeg-core.js", "ffmpeg-core.wasm"]) {
    copyFileSync(join(coreSrc, file), join(dest, file));
  }
} else {
  console.warn("[copy-ffmpeg-worker] @ffmpeg/core not installed, skipping core");
}

console.log("[copy-ffmpeg-worker] staged ffmpeg runtime in public/ffmpeg/");
